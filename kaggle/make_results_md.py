"""Regenerate RESULTS.md from every downloaded run (kaggle/results/*/runs/*/final.json).

    python kaggle/make_results_md.py
"""
import glob
import json
import os
from collections import defaultdict

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PAPER = {'kvasir': (.9380, .8881), 'clinicdb': (.9437, .8939), 'colondb': (.9255, .8659), 'polypgen': (.8683, .8211)}
TABLE3 = {'kvasir': ((.9380, 'BAMPolyp'), (.8910, 'SwinE-Net')),
          'clinicdb': ((.9521, 'PVT-EMCAD-B2'), (.9238, 'LGPS')),
          'colondb': ((.9255, 'BAMPolyp'), (.8659, 'BAMPolyp')),
          'polypgen': ((.8683, 'BAMPolyp'), (.8211, 'BAMPolyp'))}
DS = ['kvasir', 'clinicdb', 'colondb', 'polypgen']
NAME = {'kvasir': 'Kvasir-SEG', 'clinicdb': 'CVC-ClinicDB', 'colondb': 'CVC-ColonDB', 'polypgen': 'PolypGen'}
HEADLINE = 'DAXNet PVTv2-b2 @352 + presence'
SESSIONS = [
    ('main-a', 'First DAXNet vs BAMPolyp comparison (EffNet-B0, 256 px, seed 42) + Kvasir ablations',
     'On par; the paper numbers are not reproduced by the released code'),
    ('main-b', 'BAMPolyp seed 1 and PolypGen; recipe cross-over',
     'Still on par; the PolypGen gap is false positives on polyp-free frames'),
    ('main-c', 'PVTv2-b2 / PVTv2-b0 @352 + presence gate, all datasets, seed 42',
     'PVTv2-b2 beats all 8 paper numbers'),
    ('main-d', "Controlled comparison at BAMPolyp's setting (EffNet-B0, 256 px), 3 seeds; BAMPolyp seed 2",
     'DAXNet ~ BAMPolyp at equal size'),
    ('sota-all-datasets', 'Single self-contained notebook: PVTv2-b2 seeds 1 (+2)',
     'Confirms: every seed beats all 8 paper numbers'),
]


def load():
    runs = []
    for f in sorted(glob.glob(os.path.join(HERE, 'results', '*', 'runs', '*', 'final.json'))):
        d = os.path.dirname(f)
        m = json.load(open(os.path.join(d, 'meta.json')))
        session = os.path.basename(os.path.dirname(os.path.dirname(d))).replace('daxnet-', '')
        if m.get('protocol') != 'bam' or session == 'smoke' or os.path.basename(d).startswith('smoke'):
            continue
        runs.append(dict(session=session, name=os.path.basename(d), m=m, r=json.load(open(f))))
    return runs


def config(x):
    m, c = x['m'], x['m'].get('model_cfg') or {}
    if m['model'] == 'bampolyp':
        return 'BAMPolyp (reproduced)' + ('' if m['recipe'] == 'bam' else ', our recipe')
    enc = {'effb0': 'EffNet-B0', 'pvt_v2_b0': 'PVTv2-b0', 'pvt_v2_b2': 'PVTv2-b2'}[c.get('encoder', 'effb0')]
    abl = [k for k, v in (('no edge', not c.get('edge_aware', True)), ('causal', not c.get('bidirectional', True)),
                          ('s32 only', c.get('axial_scales') == ['s32'])) if v]
    s = f"DAXNet {enc} @{m['size']}" + (' + presence' if c.get('presence') else '')
    s += ', BAM recipe' if m['recipe'] == 'bam' else ''
    return s + (f" [ablation: {', '.join(abl)}]" if abl else '')


def pair(xs, k):
    v = [(x['r'][k]['dice_net'], x['r'][k]['iou_net']) for x in xs if k in x['r']]
    if not v:
        return '-'
    v = np.array(v).mean(0)
    return f'{v[0]:.4f} / {v[1]:.4f}'


def main():
    runs = load()
    L = ['# DAXNet results', '',
         "Per-image Dice / IoU at threshold 0.5 (BAMPolyp's metric) on BAMPolyp's seed-42 80/10/10 split of each dataset.",
         "* **Protocol A** (the paper's numbers): validation score of the checkpoint with the best validation IoU.",
         '* **Protocol B**: held-out 10 % test split at that same checkpoint (never used for selection).',
         '* **TTA**: the same checkpoint with horizontal / vertical flip averaging (logged from main-c on; older runs show -, and TTA means use only runs that have it).',
         '',
         'Generated by `python kaggle/make_results_md.py` from `kaggle/results/*/runs/*/final.json`.', '']

    L += ['## 1. Headline: DAXNet (PVTv2-b2, 352 px, presence gate) vs. the BAMPolyp paper', '',
          '| Dataset | BAMPolyp paper Dice / IoU | DAXNet Protocol A (mean ± std) | Seeds | Worst seed | Every seed beats paper | Protocol B test | Protocol B + TTA |',
          '|---|---|---|---|---|---|---|---|']
    for ds in DS:
        xs = [x for x in runs if config(x) == HEADLINE and x['m']['dataset'] == ds]
        if not xs:
            continue
        vd = np.array([x['r']['val']['dice_net'] for x in xs])
        vi = np.array([x['r']['val']['iou_net'] for x in xs])
        sd = lambda a: f' ± {a.std(ddof=1):.4f}' if len(a) > 1 else ''
        ok = (vd > PAPER[ds][0]).all() and (vi > PAPER[ds][1]).all()
        L.append(f"| {NAME[ds]} | {PAPER[ds][0]:.4f} / {PAPER[ds][1]:.4f} | "
                 f"**{vd.mean():.4f}{sd(vd)} / {vi.mean():.4f}{sd(vi)}** | "
                 f"{', '.join(str(x['m']['seed']) for x in xs)} | {vd.min():.4f} / {vi.min():.4f} | "
                 f"{'yes' if ok else 'NO'} | {pair(xs, 'test')} | {pair(xs, 'test_tta')} |")
    L += ['', 'DAXNet PVTv2-b2: 28.65 M parameters, 25.8 GFLOPs @352. BAMPolyp: 6.66 M parameters, 3.67 GFLOPs @256.', '',
          "### vs. the best value in BAMPolyp's Table 3", '',
          "Other methods' numbers are taken from their own papers and may use other splits (BAMPolyp says so).", '',
          '| Dataset | Table-3 best Dice | DAXNet Dice | Table-3 best IoU | DAXNet IoU |', '|---|---|---|---|---|']
    for ds in DS:
        xs = [x for x in runs if config(x) == HEADLINE and x['m']['dataset'] == ds]
        if not xs:
            continue
        vd = np.mean([x['r']['val']['dice_net'] for x in xs])
        vi = np.mean([x['r']['val']['iou_net'] for x in xs])
        (td, tdn), (ti, tin) = TABLE3[ds]
        L.append(f"| {NAME[ds]} | {td:.4f} ({tdn}) | {vd:.4f} {'✅' if vd > td else '❌'} | "
                 f"{ti:.4f} ({tin}) | {vi:.4f} {'✅' if vi > ti else '❌'} |")

    L += ['', '## 2. All configurations (mean over seeds)', '',
          '| Configuration | Dataset | Seeds | Protocol A Dice / IoU | Protocol B Dice / IoU | Protocol B + TTA |',
          '|---|---|---|---|---|---|']
    groups = defaultdict(list)
    for x in runs:
        groups[(config(x), x['m']['dataset'])].append(x)
    for c, ds in sorted(groups, key=lambda k: (DS.index(k[1]), k[0])):
        xs = groups[(c, ds)]
        L.append(f"| {c} | {NAME[ds]} | {len(xs)} | {pair(xs, 'val')} | {pair(xs, 'test')} | {pair(xs, 'test_tta')} |")

    L += ['', '## 3. Every run', '',
          '| Session | Run | Configuration | Seed | Best epoch | Hours | Protocol A Dice / IoU | Protocol B Dice / IoU |',
          '|---|---|---|---|---|---|---|---|']
    for x in sorted(runs, key=lambda x: (DS.index(x['m']['dataset']), x['session'], x['name'])):
        r = x['r']
        L.append(f"| {x['session']} | {x['name']} | {config(x)} | {x['m']['seed']} | {r['best_epoch']} | "
                 f"{r['train_hours']:.2f} | {pair([x], 'val')} | {pair([x], 'test')} |")

    L += ['', '## 4. What each Kaggle session did', '', '| Session | Purpose | Outcome |', '|---|---|---|']
    L += [f'| {s} | {p} | {o} |' for s, p, o in SESSIONS]
    L += ['', '## Pending', '',
          '* PolypGen seed 2 for DAXNet PVTv2-b2 (currently 2 seeds).',
          '* Ablation at PVTv2-b2 scale without the axial SSD blocks, to separate the operator from the encoder gain.']
    open(os.path.join(ROOT, 'RESULTS.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print(f'RESULTS.md: {len(runs)} runs')


if __name__ == '__main__':
    main()
